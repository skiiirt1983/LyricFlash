"""Rewrite the BOARD-FROM-STEP block of params.py from extracted values."""
from __future__ import annotations

import re
from pathlib import Path

START = "# >>> BOARD-FROM-STEP (generated by phase0.py, do not edit by hand)"
END = "# <<< BOARD-FROM-STEP"


def write_board_block(values, params_path: Path, step_name: str, step_sha: str) -> None:
    lines = [START, f"# Source file: {step_name} (sha1 {step_sha})", ""]
    for v in values:
        if v.value == "TODO":
            lines.append(f"# {v.name}: TODO, {v.source}")
            lines.append(f"{v.name} = None")
        else:
            unit = f" [{v.unit}]" if v.unit else ""
            lines.append(f"# {v.source}{unit}")
            lines.append(f"{v.name} = {v.value!r}")
    lines.append(END)
    text = params_path.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    params_path.write_text(pat.sub(lambda m: "\n".join(lines), text))
